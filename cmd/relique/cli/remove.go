// removalPlan lists everything a remove command will delete, built before anything is touched so that it can be
// displayed to the user for confirmation
type removalPlan struct {
	JobsToRemove   []job.Job
	ImagesToRemove []image.Image
	// Linked elements that are not removed, displayed for information
	ImagesKept []image.Image
	JobsKept   []job.Job
}

func (p removalPlan) IsEmpty() bool {
	return len(p.JobsToRemove) == 0 && len(p.ImagesToRemove) == 0
}

func (p removalPlan) FreedSpace() uint64 {
	var total uint64
	for _, img := range p.ImagesToRemove {
		total += img.SizeOnDisk
	}
	return total
}

func jobTypeString(j job.Job) string {
	switch j.JobType.Type {
	case job_type.Backup:
		return fmt.Sprintf("backup/%s", j.BackupType.String())
	case job_type.Restore:
		return "restore"
	default:
		return j.JobType.String()
	}
}

func printJobTable(title string, jobs []job.Job) {
	if len(jobs) == 0 {
		return
	}

	fmt.Printf("\n%s (%d):\n\n", title, len(jobs))
	tab := tabular.New()
	tab.Col("uuid", "UUID", 40)
	tab.Col("client", "Client", 10)
	tab.Col("module", "Module", 15)
	tab.Col("status", "Status", 10)
	tab.Col("type", "Type", 15)
	tab.Col("start_time", "Start time", 20)

	format := tab.Print("uuid", "client", "module", "status", "type", "start_time")
	for _, j := range jobs {
		fmt.Printf(
			format,
			j.Uuid,
			j.Client.String(),
			j.Module.String(),
			j.Status.String(),
			jobTypeString(j),
			utils.FormatDatetime(j.StartTime),
		)
	}
}

func printImageTable(title string, imgs []image.Image) {
	if len(imgs) == 0 {
		return
	}

	fmt.Printf("\n%s (%d):\n\n", title, len(imgs))
	tab := tabular.New()
	tab.Col("uuid", "UUID", 40)
	tab.Col("client", "Client", 25)
	tab.Col("module", "Module", 15)
	tab.Col("date", "Date", 20)
	tab.Col("size", "Size", 20)

	format := tab.Print("uuid", "client", "module", "date", "size")
	for _, img := range imgs {
		fmt.Printf(
			format,
			img.Uuid,
			img.Client.String(),
			img.Module.String(),
			utils.FormatDatetime(img.CreatedAt),
			humanize.Bytes(img.SizeOnDisk),
		)
	}
}

func printRemovalRecap(p removalPlan) {
	fmt.Println("\n# Removal recap")
	printJobTable("Jobs to remove", p.JobsToRemove)
	printImageTable("Images to remove", p.ImagesToRemove)
	printImageTable("Images generated by removed jobs that will be KEPT (use --clean-image to remove them)", p.ImagesKept)
	printJobTable("Jobs linked to removed images that will be KEPT (use --clean-job to remove them)", p.JobsKept)

	fmt.Printf(
		"\nTotal: %d job(s) and %d image(s) will be removed, %s of image data will be freed\n\n",
		len(p.JobsToRemove),
		len(p.ImagesToRemove),
		humanize.Bytes(p.FreedSpace()),
	)
}

// confirmRemoval displays the recap and asks for confirmation. Exits if the user declines.
// Returns false if there is nothing to remove.
func confirmRemoval(p removalPlan) bool {
	if p.IsEmpty() {
		fmt.Println("Nothing to remove")
		return false
	}

	printRemovalRecap(p)

	if assumeYes {
		slog.Info("Skipping confirmation on user request (-y/--yes flag provided)")
		return true
	}

	if !utils.Confirm("Confirm removal") {
		slog.Error("Removal canceled")
		os.Exit(1)
	}

	return true
}

// runRemoval calls remove for each uuid, continuing on errors, and exits with an error code if any removal failed
func runRemoval(kind string, uuids []string, remove func(uuid string) error) {
	failed := 0
	for _, uuid := range uuids {
		if err := remove(uuid); err != nil {
			failed++
			slog.With(
				slog.Any("error", err),
				slog.String("uuid", uuid),
			).Error(fmt.Sprintf("Cannot remove %s", kind))
		}
	}

	fmt.Printf("\n%d %s(s) removed, %d failed\n", len(uuids)-failed, kind, failed)
	if failed > 0 {
		os.Exit(1)
	}
}

// validateRemoveArgs ensures that exactly one of a UUID argument or --older-than is used, and that search filters
// are only used with --older-than
func validateRemoveArgs(filterFlags ...string) cobra.PositionalArgs {
	return func(cmd *cobra.Command, args []string) error {
		if err := cobra.MaximumNArgs(1)(cmd, args); err != nil {
			return err
		}

		olderThanSet := cmd.Flags().Changed("older-than")
		if len(args) == 1 && olderThanSet {
			return fmt.Errorf("cannot use both a UUID and --older-than")
		}
		if len(args) == 0 && !olderThanSet {
			return fmt.Errorf("a UUID or --older-than is required")
		}
		if len(args) == 1 {
			for _, f := range filterFlags {
				if cmd.Flags().Changed(f) {
					return fmt.Errorf("--%s can only be used with --older-than", f)
				}
			}
		}

		return nil
	}
}

// olderThanCutoff converts an age like "90d" into a datetime usable in search "Before" filters
func olderThanCutoff(olderThan string) (string, time.Time, error) {
	age, err := utils.ParseAge(olderThan)
	if err != nil {
		return "", time.Time{}, err
	}

	cutoff := time.Now().Add(-age)
	return cutoff.UTC().Format("2006-01-02 15:04:05"), cutoff, nil
}
