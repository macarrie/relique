import { useEffect, useState } from "react";
import { AxiosError, AxiosResponse } from "axios";

import Job from "../types/job";
import Image from "../types/image";
import Const from "../types/const";
import API from "../utils/api";
import Utils from "../utils/utils";
import RemoveModal from "./remove_modal";
import TextPlaceholder from "./text_placeholder";

// Asks confirmation before removing a job, with a recap of what is removed and what is kept.
// onRemoved receives the job uuid and whether the generated image was removed too.
type Props = {
    job: Job | null,
    onClose: () => void,
    onRemoved: (uuid: string, imageRemoved: boolean) => void,
};

function JobRemoveModal({ job, onClose, onRemoved }: Props) {
    const [linkedImage, setLinkedImage] = useState<Image | null>(null);
    const [linkedLoading, setLinkedLoading] = useState<boolean>(false);
    const [cleanImage, setCleanImage] = useState<boolean>(false);

    useEffect(() => {
        setCleanImage(false);
        setLinkedImage(null);
        if (!job || job.job_type !== "backup") {
            return;
        }

        // Backup jobs share their uuid with the image they generated
        setLinkedLoading(true);
        API.images.get(job.uuid).then((response: AxiosResponse<Image>) => {
            setLinkedImage(response.data);
        }).catch(() => {
            setLinkedImage(null);
        }).finally(() => {
            setLinkedLoading(false);
        });
    }, [job]);

    function remove(): Promise<unknown> {
        if (!job) {
            return Promise.resolve();
        }

        const imageRemoved = cleanImage && linkedImage !== null;
        return API.jobs.delete(job.uuid, imageRemoved).then(() => {
            Utils.notify(Const.OK, "Job removed", imageRemoved ? "Job and its image have been removed" : "Job has been removed");
            onRemoved(job.uuid, imageRemoved);
        }).catch((error: AxiosError<{ error?: string }>) => {
            console.log("Cannot remove job", error);
            const message = error.response?.status === 409 ? "Job is still running" : (error.response?.data?.error ?? error.toString());
            Utils.notify(Const.CRITICAL, "Cannot remove job", message);
            throw error;
        });
    }

    return (
        <RemoveModal
            open={job !== null}
            title="Job removal"
            confirmLabel={cleanImage && linkedImage ? "Delete job and image" : "Delete job"}
            confirmDisabled={linkedLoading}
            onConfirm={remove}
            onClose={onClose}
        >
            <p>The following job will be removed, with its logs and statistics:</p>
            <table className="table table-sm">
                <tbody>
                    <tr><td>ID</td><td className="code">{job?.uuid}</td></tr>
                    <tr><td>Client</td><td>{job?.client?.name}</td></tr>
                    <tr><td>Module</td><td>{job?.module?.name}</td></tr>
                    <tr><td>Type</td><td>{job?.job_type}{job?.job_type === "backup" && ` (${job?.backup_type})`}</td></tr>
                    <tr><td>Status</td><td>{job?.status}</td></tr>
                    <tr><td>Start time</td><td>{job && Utils.formatDate(job.start_time)}</td></tr>
                </tbody>
            </table>

            {linkedLoading && <TextPlaceholder />}
            {!linkedLoading && linkedImage && (
                <div className="space-y-2">
                    <label className="label cursor-pointer text-base-content">
                        <input type="checkbox" className="checkbox checkbox-error checkbox-sm" checked={cleanImage} onChange={e => setCleanImage(e.target.checked)} />
                        Also remove the image generated by this job ({Utils.formatSize(linkedImage.size_on_disk)})
                    </label>
                    {cleanImage ? (
                        <p className="text-sm">
                            Backup data (<b>{Utils.formatSize(linkedImage.size_on_disk)}</b>) will be permanently deleted from repository <b>{linkedImage.repository?.name}</b>.
                        </p>
                    ) : (
                        <p className="text-sm text-base-content/70">
                            The image generated by this job is kept and can still be used for restores.
                        </p>
                    )}
                </div>
            )}
        </RemoveModal>
    );
}

export default JobRemoveModal;
